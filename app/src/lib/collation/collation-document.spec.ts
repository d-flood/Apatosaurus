function makeWitness(witnessId: string, content: string, isBaseText = false): WitnessConfig {
	return {
		witnessId,
		siglum: witnessId,
		transcriptionId: `${witnessId}-tx`,
		content,
		tokens: content
			.split(/\s+/)
			.filter(Boolean)
			.map(token => ({
				kind: 'text',
				original: token,
				segments: [
					{
						text: token,
						hasUnclear: false,
						isPunctuation: false,
						isSupplied: false,
					},
				],
				gap: null,
			})),
		treatment: 'inherit',
		isBaseText,
		isExcluded: false,
		overridesDefault: false,
	};
}

function makeClassifiedReading(
	id: string,
	text: string,
	witnessIds: string[],
	order: number
): ClassifiedReading {
	return {
		id,
		order,
		label: '',
		text,
		normalizedText: text,
		witnessIds,
		witnessGroups: [{ id: `g-${id}`, witnessIds }],
		isOmission: false,
		isLacuna: false,
		readingType: null,
		certainty: null,
		parentReadingId: null,
		isSubreading: false,
		autoGenerated: false,
		derivedFromRuleIds: [],
	};
}

