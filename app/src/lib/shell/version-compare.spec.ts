import { describe, expect, it } from 'vitest';

import type { ClassifiedReading } from '$lib/collation/collation-types';
import type { StoredTranscriptionDocument } from '$lib/transcription/content';
import {
	compareCollations,
	compareTranscriptions,
	formatCollationPart,
	formatTranscriptionPart,
	type ComparableCollation,
} from './version-compare';

function transcription(verses: Array<[string, string]>): StoredTranscriptionDocument {
	return {
		type: 'transcriptionDocument',
		pages: [
			{
				type: 'page',
				id: 'page-1',
				columns: [
					{
						type: 'column',
						number: 1,
						lines: verses.map(([verse, text], index) => ({
							type: 'line' as const,
							number: index + 1,
							items: [
								{
									type: 'milestone' as const,
									kind: 'verse' as const,
									attrs: { book: 'John', chapter: '1', verse },
								},
								{ type: 'text' as const, text },
							],
						})),
					},
				],
			},
		],
	};
}

function reading(id: string, text: string): ClassifiedReading {
	return {
		id,
		order: 0,
		label: id,
		text,
		normalizedText: text,
		witnessIds: ['w1'],
		witnessGroups: [],
		isOmission: false,
		isLacuna: false,
		readingType: null,
		certainty: null,
		parentReadingId: null,
		isSubreading: false,
		autoGenerated: true,
		derivedFromRuleIds: [],
	};
}

function cell(text: string) {
	return {
		text,
		regularizedText: text,
		alignmentValue: text,
		sourceTokenIds: [],
		kind: 'text' as const,
		gap: null,
		isOmission: false,
		isLacuna: false,
		isRegularized: false,
		ruleIds: [],
		regularizationTypes: [],
	};
}

function alignment(columns: Array<[string, string, string]>): ComparableCollation['alignment'] {
	return {
		type: 'alignment',
		witnessOrder: ['w1', 'w2'],
		columns: columns.map(([id, first, second], index) => ({
			id,
			index,
			cells: [
				['w1', cell(first)],
				['w2', cell(second)],
			],
			merged: false,
		})),
	};
}

function unit(columnId: string, text: string) {
	return {
		type: 'variationUnit' as const,
		id: `unit:${columnId}`,
		unitId: `unit:${columnId}`,
		columnId,
		readings: [reading('a', text), reading('b', `${text}2`)],
		decisions: { lemmaReadingId: 'a' },
	};
}

const settings: ComparableCollation['settings'] = {
	regularizationRules: [],
	ignoreWordBreaks: false,
	lowercase: true,
	ignoreTokenWhitespace: false,
	ignorePunctuation: false,
	suppliedTextMode: 'clear',
	segmentation: false,
};

function collation(
	units: ReturnType<typeof unit>[],
	overrides: Partial<ComparableCollation> = {}
): ComparableCollation {
	return {
		alignment: null,
		apparatus: { type: 'apparatus', units },
		stemma: null,
		settings,
		...overrides,
	};
}

describe('compareTranscriptions', () => {
	it('splits per verse and reports unchanged verses as not differing', () => {
		const left = transcription([
			['1', 'en arche'],
			['2', 'houtos en'],
		]);
		const right = transcription([
			['1', 'en arche'],
			['2', 'houtos hn'],
		]);

		const parts = compareTranscriptions(left, right);

		expect(parts.map(part => [part.key, part.differs])).toEqual([
			['John 1:1', false],
			['John 1:2', true],
		]);
		expect(formatTranscriptionPart(parts[1].left)).toBe('houtos en');
		expect(formatTranscriptionPart(parts[1].right)).toBe('houtos hn');
	});

	it('accepts serialized content and reports one-sided verses with a null side', () => {
		const left = JSON.stringify(transcription([['1', 'en arche']]));
		const right = transcription([
			['1', 'en arche'],
			['3', 'panta'],
		]);

		const parts = compareTranscriptions(left, right);

		expect(parts).toHaveLength(2);
		expect(parts[1]).toMatchObject({ key: 'John 1:3', left: null, differs: true });
		expect(compareTranscriptions(null, right).every(part => part.left === null)).toBe(true);
	});
});

describe('compareCollations', () => {
	it('keys units by stable id and reports unchanged units and settings as not differing', () => {
		const parts = compareCollations(
			collation([unit('c1', 'en'), unit('c2', 'arche')]),
			collation([unit('c1', 'en'), unit('c2', 'arche')])
		);

		expect(parts.map(part => [part.key, part.label, part.differs])).toEqual([
			['unit:c1', 'en', false],
			['unit:c2', 'arche', false],
			['settings', 'Collation settings', false],
		]);
	});

	it("keeps a unit's key when units elsewhere are reordered", () => {
		const parts = compareCollations(
			collation([unit('c1', 'en'), unit('c2', 'arche'), unit('c3', 'logos')]),
			collation([unit('c3', 'logos'), unit('c1', 'en'), unit('c2', 'arche')])
		);

		expect(parts.find(part => part.key === 'unit:c2')).toMatchObject({ differs: false });
		expect(parts.every(part => !part.differs)).toBe(true);
	});

	it('carries decisions, local stemma and connectivity with the unit', () => {
		const left = collation([unit('c1', 'en'), unit('c2', 'arche')]);
		const right = collation([unit('c1', 'en'), unit('c2', 'arche')], {
			stemma: {
				type: 'stemma',
				units: [
					{
						type: 'stemmaUnit',
						id: 'unit:c2',
						unitId: 'unit:c2',
						columnId: 'c2',
						arcs: [{ id: 'arc', priorReadingId: 'a', posteriorReadingId: 'b' }],
						connectivity: 5,
					},
				],
			},
		});
		right.apparatus!.units[0].decisions = { lemmaReadingId: 'b' };

		const parts = compareCollations(left, right);

		expect(parts.map(part => [part.key, part.differs])).toEqual([
			['unit:c1', true],
			['unit:c2', true],
			['settings', false],
		]);
		expect(formatCollationPart(parts[1].right)).toContain('a → b');
		expect(formatCollationPart(parts[1].right)).toContain('Connectivity: 5');
	});

	it('treats variant alignment columns as units before any readings are saved', () => {
		const left = collation([], {
			apparatus: null,
			alignment: alignment([
				['c1', 'en', 'en'],
				['c2', 'arche', 'archh'],
				['c3', 'logos', 'logos'],
			]),
		});
		const right = collation([], {
			apparatus: null,
			alignment: alignment([
				['c0', 'kai', 'kai'],
				['c1', 'en', 'en'],
				['c2', 'arche', 'archh'],
				['c3', 'logos', 'logou'],
			]),
		});

		const parts = compareCollations(left, right);

		expect(parts.map(part => [part.key, part.label, part.differs])).toEqual([
			['unit:c2', 'arche', false],
			['unit:c3', 'logos', true],
			['settings', 'Collation settings', false],
		]);
		expect(formatCollationPart(parts[1].right)).toContain('logou  (1 wit.)');
	});

	it('reports units on one side only and settings changes', () => {
		const parts = compareCollations(
			collation([unit('c1', 'en')]),
			collation([unit('c1', 'en'), unit('c2', 'arche')], {
				settings: { ...settings, lowercase: false },
			})
		);

		expect(parts.map(part => [part.key, part.differs])).toEqual([
			['unit:c1', false],
			['unit:c2', true],
			['settings', true],
		]);
		expect(parts[1].left).toBeNull();
	});
});
